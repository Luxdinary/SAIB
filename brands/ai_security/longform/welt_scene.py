"""The "Nachtarchiv" world of the week before (welt.js, betrieb.js, dokumente.js and the acts of video 01) as a
scene inside the long-form composer.

Copies of the original files live in longform/welt/ (source: OneDrive\\scutoria\\marketing\\youtube\\ANIMATION,
state 31.10.2026; the original folder is not touched). welt.js computes every frame from the time (render(t), a pure
function). Here the world runs on the *global* video timeline: all chapters' word timings are joined with the
chapter offsets, so the acts find their word anchors exactly as in the week before. A chapter project embeds the
world and shows the window [offset, offset + chapter length]; HyperFrames drives it through a GSAP tween on a proxy
object whose setter calls render(offset + t) (setters run on every seek, callbacks may be suppressed).
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
WELT = HERE / "welt"
LIBS = ["lib/welt.js", "lib/betrieb.js", "lib/dokumente.js"]
OLD_ACTS = ["teil-1.js", "teil-2.js", "teil-3a.js", "teil-3b.js", "teil-3c.js", "teil-4.js", "teil-5.js", "teil-6.js", "teil-7.js"]
NL = "\n"


def global_words(timed: dict, order: list[str]) -> tuple[list[dict], dict[str, float], float]:
    """window.WOERTER for the whole video: {w, s, e, m} with absolute times; returns words, chapter offsets, total."""
    words, offsets, t = [], {}, 0.0
    for cid in order:
        tm = timed[cid]
        offsets[cid] = round(t, 3)
        for w in tm["words"]:                      # already shifted by the chapter's vstart
            words.append({"w": w.text, "s": round(t + w.start, 3), "e": round(t + w.end, 3), "m": 1})
        t += tm["total"]
    return words, offsets, round(t, 3)


def world_files(plan: dict) -> tuple[str, list[str], list[str]]:
    """Folder of the video's acts and its data/library files: (welt_dir, welt_data loaded before the libraries,
    welt_libs loaded after them). Defaults are the files of video 01."""
    return plan.get("welt_dir", "video-01"), plan.get("welt_data", []), plan.get("welt_libs", [])


def acts_for(plan: dict) -> list[str]:
    """Act files in speaking order: new acts named in the plan (chapter key "welt_acts") or the old acts of video 01."""
    acts: list[str] = []
    for ch in plan["chapters"]:
        acts += ch.get("welt_acts", [])
    return acts or OLD_ACTS


def copy_assets(project: Path, plan: dict, words: list[dict], total: float) -> None:
    """Copy the world and the global word timings into the project (call after compose.build, which wipes it).
    welt.js adds NACHLAUF (20 s end image in teil-7.js) after TON.dauer, so dauer is the video length without the
    last chapter's end_seconds."""
    total = round(total - float(plan["chapters"][-1].get("end_seconds", 0.0)), 3)
    dst = project / "assets" / "welt"
    dst.mkdir(parents=True, exist_ok=True)
    for f in LIBS:
        shutil.copy2(WELT / f, dst / Path(f).name)
    wdir, data, libs = world_files(plan)
    for f in ["marken.js", *data, *libs, *acts_for(plan)]:
        src = WELT / wdir / f
        if not src.exists():
            src = WELT / "akte" / f                # new acts written for the long version
        shutil.copy2(src, dst / Path(f).name)
    ton = json.dumps({"sprache": plan["lang"], "dauer": total, "modell": "large-v3"})
    lines = ["// generated by longform/welt_scene.py from the chapter voices (Whisper large-v3), global video time",
             f"window.TON = {ton};",
             f"window.WOERTER = {json.dumps(words, ensure_ascii=False)};", ""]
    (dst / "woerter.js").write_text(NL.join(lines), encoding="utf-8")


def layer(plan: dict, offset: float, length: float) -> dict:
    """HTML for the stage, the boot script and the timeline line that drives the world (no file IO)."""
    _, data, libs = world_files(plan)
    scripts = ["woerter.js", "marken.js", *data, "welt.js", "betrieb.js", "dokumente.js", *libs, *acts_for(plan)]
    loader = NL.join(f'<script src="assets/welt/{s}"></script>' for s in scripts)
    stage = (f'<div id="welt" class="clip" data-start="0" data-duration="{length:.3f}" data-track-index="1">'
             '<svg id="stage" width="1920" height="1080" viewBox="0 0 1920 1080" xmlns="http://www.w3.org/2000/svg"></svg></div>')
    boot = NL.join([loader, "<script>",
                    "(function(){ try { aufbauen(); } catch (e) { console.log('welt aufbauen: ' + e.message); }",
                    f"  window.WELT_OFFSET = {offset:.3f}; render(window.WELT_OFFSET); }})();",
                    "</script>"])
    drive = NL.join([
        f"const weltProxy = {{ _t: 0, get t() {{ return this._t; }}, set t(v) {{ this._t = v; render({offset:.3f} + v); }} }};",
        f'tl.fromTo(weltProxy, {{ t: 0 }}, {{ t: {length:.3f}, duration: {length:.3f}, ease: "none" }}, 0);'])
    return {"stage_html": stage, "boot_html": boot, "drive_js": drive}

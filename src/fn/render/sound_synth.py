def _pad_tone(n: int, freq: float, partials: list[float], detune_cents: float, rng: np.random.Generator,
              vib_hz: float = 0.15) -> np.ndarray:
    """Stereo pad tone (n, 2): partials with a +/- detuned copy per channel, slow vibrato and tremolo."""
    t = _t(n)
    out = np.zeros((n, 2))
    vib = 1.0 + 0.0017 * np.sin(2 * np.pi * vib_hz * t + rng.random() * 6.283)      # +/- 3 cents
    trem = 1.0 - 0.08 * (0.5 - 0.5 * np.cos(2 * np.pi * 0.08 * t + rng.random() * 6.283))
    d = 2 ** (detune_cents / 1200.0)
    for k, amp in enumerate(partials, start=1):
        a = amp / (1.0 + 0.15 * k)
        for ch, det in ((0, d), (1, 1.0 / d)):
            ph = 2 * np.pi * np.cumsum(freq * k * det * vib) / SR + rng.random() * 6.283
            out[:, ch] += a * np.sin(ph)
    return out * trem[:, None]


def _pluck(n: int, freq: float, kind: str) -> np.ndarray:
    t = _t(n)
    if kind == "pluck":
        y = (np.sin(2 * np.pi * freq * t) + 0.33 * np.sin(2 * np.pi * 3 * freq * t) + 0.2 * np.sin(2 * np.pi * 5 * freq * t))
        return y * np.exp(-t / 0.14) * np.clip(t / 0.002, 0, 1)
    y = np.sin(2 * np.pi * freq * t) + 0.3 * np.sin(2 * np.pi * 2 * freq * t)
    return y * np.exp(-t / 0.30) * np.clip(t / 0.004, 0, 1)


def music_bed(seconds: float, mood: str = DEFAULT_MOOD, seed: int = 0, *, end_at: float | None = None,
              final_chord: bool = False, fade_in: float = 1.5, fade_out: float = 2.5) -> np.ndarray:
    """Procedural music bed, float32 stereo (n, 2) at 48 kHz, peak -6 dBFS; `seconds` long, silent after `end_at`.

    Additive chord pads (detuned partials, slow vibrato), a sub octave on the lowest chord tone, a soft pulse or
    pluck on the beat grid, optional eighth-note arpeggio, filtered noise "air", global low-pass. Chord changes
    overlap by 1.5 s (raised-cosine crossfade). `final_chord` holds the tonic for the last 3.5 s before `end_at`.
    """
    m = MOODS.get(mood) or MOODS[DEFAULT_MOOD]
    rng = np.random.default_rng(int(seed) & 0xFFFFFFFF)
    n_total = int(SR * seconds)
    end = min(float(end_at) if end_at is not None else float(seconds), float(seconds))
    out = np.zeros((n_total, 2))
    beat = 60.0 / m["bpm"]
    seg = beat * 4 * m["bars_per_chord"]
    xf = 1.5
    root = float(m["root"])
    prog = m["progression"]

    # chord schedule: (start, chord); the tonic takes over 3.5 s before the end when asked for
    schedule: list[tuple[float, list[int]]] = []
    t0, k = 0.0, 0
    while t0 < end:
        schedule.append((t0, prog[k % len(prog)]))
        t0 += seg
        k += 1
    if final_chord and end > 4.0:
        cut = end - 3.5
        schedule = [(s, c) for s, c in schedule if s < cut] + [(cut, prog[0])]
    # pads with crossfade
    for i, (s, chord) in enumerate(schedule):
        s_end = schedule[i + 1][0] if i + 1 < len(schedule) else end
        a, b = max(0.0, s - xf / 2), min(end, s_end + xf / 2)
        n = int((b - a) * SR)
        if n <= 0:
            continue
        pad = np.zeros((n, 2))
        for semi in chord:
            pad += _pad_tone(n, root * 2 ** (semi / 12.0), m["partials"], m["detune_cents"], rng)
        sub = np.sin(2 * np.pi * np.cumsum(np.full(n, root * 2 ** (chord[0] / 12.0 - 1))) / SR)
        pad += 0.40 * sub[:, None] * np.array([[1.0, 1.0]])
        pad /= max(1.0, len(chord) * 0.9)
        pad = fade(pad, xf if a > 0 else 0.0, xf if b < end else 0.0)
        i0 = int(a * SR)
        out[i0:i0 + n] += pad[: n_total - i0]
    # pulse / pluck on the beat grid, arpeggio in eighths
    grid = np.arange(0.0, end, beat)
    pl_n = int(SR * 0.6)
    for j, tb in enumerate(grid):
        s_idx = max(i for i, (s, _) in enumerate(schedule) if s <= tb + 1e-9) if schedule else 0
        chord = schedule[s_idx][1]
        i0 = int(tb * SR)
        if m["pulse"] and j % int(m["pulse_every"]) == 0:
            semi = chord[0] + (12 if m["pulse"] == "soft" else 0)
            if m["pulse"] == "soft" and (j // int(m["pulse_every"])) % 2 == 1:
                semi = chord[2] if len(chord) > 2 else chord[0]
            y = _pluck(pl_n, root * 2 ** (semi / 12.0), m["pulse"]) * (0.36 if m["pulse"] == "soft" else 0.30)
            out[i0:i0 + pl_n, 0] += y[: n_total - i0] * 0.9
            out[i0:i0 + pl_n, 1] += y[: n_total - i0] * 1.0
        if m["arp"]:
            for h in (0, 1):
                ta = tb + h * beat / 2
                if ta >= end:
                    continue
                semi = chord[(2 * j + h) % len(chord)] + 12
                ya = _pluck(int(SR * 0.35), root * 2 ** (semi / 12.0), "soft") * 0.14
                ia = int(ta * SR)
                out[ia:ia + len(ya), h] += ya[: n_total - ia] * 0.7
                out[ia:ia + len(ya), 1 - h] += ya[: n_total - ia] * 0.4
    # air: low-passed noise with a slow swell
    n_end = int(end * SR)
    if n_end > 0 and m["air"] > 0:
        air = lowpass_fft(rng.standard_normal(n_end), 900.0, 1.2)
        air *= (0.7 + 0.3 * np.sin(2 * np.pi * 0.05 * _t(n_end) + rng.random() * 6.283))
        out[:n_end, 0] += m["air"] * air
        out[:n_end, 1] += m["air"] * lowpass_fft(rng.standard_normal(n_end), 900.0, 1.2) * 0.9 + m["air"] * 0.3 * air
    # global tone and envelope
    for ch in (0, 1):
        out[:, ch] = lowpass_fft(out[:, ch], float(m["lowpass"]), 1.0)
    out -= np.mean(out, axis=0, keepdims=True)
    env = np.ones(n_total)
    n_in = int(fade_in * SR)
    if n_in > 0:
        env[:n_in] = 0.5 - 0.5 * np.cos(np.pi * np.arange(n_in) / n_in)
    e_end = int(end * SR)
    n_out = int(min(fade_out, end) * SR)
    if n_out > 0:
        env[e_end - n_out:e_end] *= 0.5 + 0.5 * np.cos(np.pi * np.arange(n_out) / n_out)
    env[e_end:] = 0.0
    out *= env[:, None]
    return normalize(out, -6.0).astype(np.float32)



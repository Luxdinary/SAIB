"""Brand LAYER / MANIFEST_EXTRA hooks and the optional sound-effect track."""
from fn.direction import story
from fn.render import assets, brand_scenes, templates


class _Brand:
    def __init__(self, d):
        self.dir = d


def test_layer_and_manifest_extra(tmp_path, monkeypatch):
    (tmp_path / "demo").mkdir()
    (tmp_path / "demo" / "scenes.py").write_text(
        "TEMPLATES = {}\n"
        "def LAYER(plan, brand, project_dir, captions):\n"
        "    return {'under_scenes_html': '<canvas id=\"gl\"></canvas>', 'events': [1.5], 'problems': []}\n"
        "def MANIFEST_EXTRA(plan):\n"
        "    return {'calculations': [{'what': 'height', 'value': 828}], 'risk_level': 'low'}\n", encoding="utf-8")
    monkeypatch.setattr(brand_scenes, "BRANDS_DIR", tmp_path)
    brand_scenes._cache.clear()
    out = brand_scenes.layer_for("demo", None, None, tmp_path, [])
    assert out["under_scenes_html"].startswith("<canvas") and out["events"] == [1.5]
    assert brand_scenes.manifest_extra("demo", None)["calculations"][0]["value"] == 828
    assert brand_scenes.layer_for("other", None, None, tmp_path, []) == {}
    brand_scenes._cache.clear()


def test_sfx_resolve_with_licence(tmp_path):
    sfx = tmp_path / "assets" / "sfx"
    sfx.mkdir(parents=True)
    (sfx / "pop.wav").write_bytes(b"RIFF")
    (sfx / "boing.wav").write_bytes(b"RIFF")
    (sfx / "LICENSE.md").write_text("pop.wav: generated by fn (sine burst), no third-party material\n", encoding="utf-8")
    plan = story.DirectionPlan("v", "demo", "de", "t", [])
    aset = assets.resolve_assets(plan, _Brand(tmp_path), {"sfx": [{"at": 1.0, "file": "pop.wav", "volume": 0.3},
                                                                   {"at": 2.0, "file": "boing.wav"},
                                                                   {"at": 3.0, "file": "missing.wav"}]})
    assert not aset.enabled and len(aset.sfx) == 2
    assert any("missing.wav" in p for p in aset.problems) and any("boing.wav" in p and "licence" in p for p in aset.problems)
    a, lic = aset.manifest_entries()
    assert {"name": "sfx:pop.wav", "kind": "audio", "role": "sfx"} in a and any(x["asset"] == "sfx:pop.wav" for x in lic)


def test_signal_fallbacks_are_real_colours():
    pal = {"accent": "#ff43c0", "text": "#ffffff", "surface": "#1a1a1a", "muted": "#999999", "bg": "#101010"}
    css = templates.scene_css(pal, "D", 800, "B", "M", 290, 910, False)
    assert "{amber}" not in css and "{on_amber}" not in css and "{red}" not in css

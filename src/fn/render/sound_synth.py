"""Procedural audio for the sound layer (Tonebene): sound effects and a music bed, synthesised with numpy.

No samples, no downloads, no third-party material: every sound is a mathematical construction (filtered noise
sweeps, damped sines, additive chord pads). Deterministic: a fixed seed per sound, so the files can be
regenerated byte-identical at any time.

Sound effects (48 kHz mono 16 bit, peak -3 dBFS, under assets/sfx/ with LICENSE.md):

    .venv\\Scripts\\python.exe -m fn.render.sound_synth sfx          # writes assets/sfx/*.wav + LICENSE.md
    .venv\\Scripts\\python.exe -m fn.render.sound_synth bed calm 20 out.wav   # 20 s bed for listening

Music bed: `music_bed(seconds, mood, seed)` returns float32 stereo at 48 kHz; fn.render.sound calls it at render
time (the bed is never stored under assets/, only in the render folder next to the mix).
"""

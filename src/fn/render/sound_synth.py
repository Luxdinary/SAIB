def render_sfx(name: str) -> np.ndarray:
    fn, seed, _ = SFX[name]
    return normalize(fn(np.random.default_rng(seed)), SFX_PEAK_DB)


def write_sfx_set(out_dir: Path, names: list[str] | None = None) -> list[Path]:
    """Write all (or the named) sound effects plus LICENSE.md into `out_dir`."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for name in names or list(SFX):
        written.append(write_wav(out_dir / f"{name}.wav", render_sfx(name)))
    lines = [
        "# Lizenz der Soundeffekte (gemeinsamer Renderer)",
        "",
        f"Alle Dateien in diesem Ordner sind mit `src/fn/render/sound_synth.py` (Version {GENERATOR_VERSION}) aus Rauschen "
        "und Sinuswellen synthetisiert (numpy, fester Zufallsstartwert je Klang, 48 kHz mono 16 bit, Spitze -3 dBFS). "
        "Keine Samples, keine Fremdaufnahmen, keine Downloads, keine Rechte Dritter.",
        f"Erzeugt am {_dt.date.today().isoformat()} von Claude Code fuer Stefan Dallinger; frei verwendbar in allen Videos des Netzes.",
        "Neu erzeugen (byte-identisch): `.venv\\Scripts\\python.exe -m fn.render.sound_synth sfx`",
        "",
        "Eine Zeile je Datei (Format `<datei>: <lizenztext>`, wie fn.render.assets es liest):",
        "",
    ]
    for name, (fn, seed, desc) in SFX.items():
        lines.append(f"{name}.wav: {SFX_LICENSE}; Funktion `{fn.__name__}`, Seed {seed}, {desc}")
    (out_dir / "LICENSE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

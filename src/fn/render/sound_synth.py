# Each function: (rng) -> mono float array at SR, not yet normalised. Parameters are listed in LICENSE.md.

def _sweep_noise(rng: np.random.Generator, seconds: float, fc: list[float], bw: float | list[float],
                 peak_at: float, attack_pow: float = 1.6, tail_pow: float = 2.2) -> np.ndarray:
    n = int(SR * seconds)
    x = rng.standard_normal(n)
    y = stft_filter(x, fc, bw)
    u = np.arange(n) / n
    # hump with its peak at `peak_at`: beta exponents chosen so that the mode sits there
    a = attack_pow
    b = a * (1.0 - peak_at) / max(peak_at, 1e-3)
    return y * bump(u, a, b) ** (tail_pow / 2.0)


def sfx_whoosh(rng: np.random.Generator) -> np.ndarray:
    """Rising whoosh: noise band 260 -> 2600 -> 900 Hz, 0.85 s, peak at 40 %, low body under it."""
    y = _sweep_noise(rng, 0.85, [260, 900, 2600, 1500, 900], 1.3, 0.40)
    body = _sweep_noise(rng, 0.85, [140, 220, 180], 1.0, 0.45) * 0.45
    return y + body


def sfx_whoosh2(rng: np.random.Generator) -> np.ndarray:
    """Falling whoosh (the answer to `whoosh`): 2400 -> 320 Hz, 0.8 s, peak at 35 %."""
    y = _sweep_noise(rng, 0.80, [2400, 1600, 700, 320], 1.3, 0.35)
    body = _sweep_noise(rng, 0.80, [200, 150], 1.0, 0.4) * 0.4
    return y + body


def sfx_swipe(rng: np.random.Generator) -> np.ndarray:
    """Short bright swipe: 900 -> 4200 Hz, 0.42 s, peak at 30 %."""
    return _sweep_noise(rng, 0.42, [900, 2400, 4200, 3000], 1.0, 0.30, attack_pow=1.3, tail_pow=2.6)


def sfx_swipe2(rng: np.random.Generator) -> np.ndarray:
    """Short swipe the other way: 3800 -> 1100 Hz, 0.4 s, peak at 28 %."""
    return _sweep_noise(rng, 0.40, [3800, 2200, 1100], 1.0, 0.28, attack_pow=1.3, tail_pow=2.6)


def sfx_click(rng: np.random.Generator) -> np.ndarray:
    """Dry click: 1.5 ms noise burst around 3 kHz plus damped sines at 1900 and 3400 Hz (tau 12 / 5 ms)."""
    n = int(SR * 0.09)
    t = _t(n)
    burst = stft_filter(rng.standard_normal(n) * np.exp(-t / 0.0015), 3000, 2.0, n_fft=512, hop=128)
    tone = np.sin(2 * np.pi * 1900 * t) * np.exp(-t / 0.012) + 0.5 * np.sin(2 * np.pi * 3400 * t) * np.exp(-t / 0.005)
    return burst * 1.2 + tone * 0.8


def sfx_tick(rng: np.random.Generator) -> np.ndarray:
    """Tiny tick: 1 ms burst around 4.5 kHz plus a 4200 Hz sine, tau 4 ms (quieter by role level, not by file)."""
    n = int(SR * 0.045)
    t = _t(n)
    burst = stft_filter(rng.standard_normal(n) * np.exp(-t / 0.001), 4500, 1.6, n_fft=512, hop=128)
    tone = np.sin(2 * np.pi * 4200 * t) * np.exp(-t / 0.004)
    return burst + tone * 0.6


def sfx_stamp(rng: np.random.Generator) -> np.ndarray:
    """Stamp: thump with pitch drop 150 -> 55 Hz (tau 110 ms) plus a 12 ms slap of noise at 0.9-3.5 kHz."""
    n = int(SR * 0.40)
    t = _t(n)
    f = 55 + 95 * np.exp(-t / 0.045)
    thump = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.11)
    slap = stft_filter(rng.standard_normal(n) * np.exp(-t / 0.012), [1800, 1200], 1.8, n_fft=512, hop=128)
    return thump * 1.0 + slap * 0.55


def sfx_paper(rng: np.random.Generator) -> np.ndarray:
    """Paper rustle: noise with sparse crackles, band 1.2-2.6 kHz wandering, two swells over 0.6 s."""
    n = int(SR * 0.60)
    t = _t(n)
    u = t / t[-1]
    spikes = (rng.random(n) < 0.0045).astype(float)
    kern = np.exp(-np.arange(int(SR * 0.004)) / (SR * 0.0012))
    crackle = 1.0 + 3.0 * np.convolve(spikes, kern)[:n]
    x = rng.standard_normal(n) * crackle
    y = stft_filter(x, [1200, 2600, 1800, 2200], 2.2, n_fft=1024, hop=256)
    env = 0.6 * bump(u, 2.0, 6.0) + bump(np.clip((u - 0.35) / 0.65, 0, 1), 1.6, 2.4)
    return y * env


def sfx_pop(rng: np.random.Generator) -> np.ndarray:
    """Pop: sine drop 620 -> 240 Hz, tau 45 ms, with a quarter of second harmonic."""
    n = int(SR * 0.14)
    t = _t(n)
    f = 240 + 380 * np.exp(-t / 0.03)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return (np.sin(ph) + 0.25 * np.sin(2 * ph)) * np.exp(-t / 0.045) * np.clip(t / 0.002, 0, 1)


def sfx_thud(rng: np.random.Generator) -> np.ndarray:
    """Soft thud: 85 -> 48 Hz sine, tau 130 ms, with a whisper of low noise (for a calm close)."""
    n = int(SR * 0.33)
    t = _t(n)
    f = 48 + 37 * np.exp(-t / 0.05)
    tone = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.13)
    air = stft_filter(rng.standard_normal(n) * np.exp(-t / 0.03), 160, 1.0, n_fft=1024, hop=256)
    return tone + air * 0.25


def sfx_chime(rng: np.random.Generator) -> np.ndarray:
    """Chime: C6, G6, C7 sines (tau 300 / 250 / 180 ms), 5 ms attack, very slightly detuned."""
    n = int(SR * 0.9)
    t = _t(n)
    y = np.zeros(n)
    for f, tau, amp in ((1046.5, 0.30, 1.0), (1568.0, 0.25, 0.55), (2093.0, 0.18, 0.3)):
        y += amp * np.sin(2 * np.pi * f * 1.001 * t) * np.exp(-t / tau)
    return y * np.clip(t / 0.005, 0, 1)


def sfx_riser(rng: np.random.Generator) -> np.ndarray:
    """Riser: noise band climbing 180 -> 3200 Hz over 1.3 s with a crescendo, plus a sine rising 110 -> 440 Hz."""
    n = int(SR * 1.3)
    t = _t(n)
    u = t / t[-1]
    noise = stft_filter(rng.standard_normal(n), [180, 500, 1400, 3200], 1.2)
    f = 110 * (4.0 ** u)
    tone = np.sin(2 * np.pi * np.cumsum(f) / SR) * 0.35
    env = u ** 2.2 * np.where(u > 0.97, (1 - u) / 0.03, 1.0)
    return (noise + tone) * env



"""Frontlore background images (own work, generated, no third-party material): olive survey map with contour lines.

Writes brands/military_history/assets/bg/
  base.jpg      1320 x 2280  daylight gradient (light from top left), paper fibre noise, survey grid
  contours.png  1320 x 2280  transparent contour lines (every 5th line stronger) and a dashed line with station ticks

The layer (frontlore_scenes.LAYER) places both 120 px beyond the frame and moves them at different speeds (parallax).
Run once after a palette change:  .venv\\Scripts\\python.exe brands\\military_history\\make_background.py
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

OUT = Path(__file__).resolve().parent / "assets" / "bg"
W, H = 1320, 2280
BG = (0x29, 0x35, 0x2D)
LINE = (0xA9, 0xB2, 0x9F)
SEED = 1833


def _field(rng: np.random.Generator) -> np.ndarray:
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    f = np.zeros((H, W), np.float32)
    for _ in range(16):                                   # hills and hollows
        cx, cy = rng.uniform(-100, W + 100), rng.uniform(-100, H + 100)
        sx, sy = rng.uniform(160, 420), rng.uniform(160, 420)
        f += rng.uniform(-1.0, 1.3) * np.exp(-(((x - cx) / sx) ** 2 + ((y - cy) / sy) ** 2))
    f += 0.18 * np.sin(x / 210 + 0.7) * np.cos(y / 260)  # gentle ridges
    return f


def base() -> Image.Image:
    rng = np.random.default_rng(SEED)
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    # daylight from top left, darker edges (no glow, just a value gradient)
    d = np.sqrt(((x - W * 0.25) / W) ** 2 + ((y - H * 0.18) / H) ** 2)
    light = np.clip(1.18 - 0.62 * d, 0.62, 1.18)
    img = np.stack([np.full((H, W), c, np.float32) for c in BG], -1) * light[..., None]
    img += rng.normal(0, 2.6, (H, W, 1)).astype(np.float32)                    # paper fibre noise
    streak = np.repeat(rng.normal(0, 1.4, (1, W)), H, 0).astype(np.float32)    # faint vertical fibres
    img += streak[..., None]
    im = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "RGB")
    dr = ImageDraw.Draw(im, "RGBA")
    for gx in range(0, W, 120):                                                # survey grid
        dr.line([(gx, 0), (gx, H)], fill=(230, 233, 229, 12), width=1)
    for gy in range(0, H, 120):
        dr.line([(0, gy), (W, gy)], fill=(230, 233, 229, 12), width=1)
    for gx in range(0, W, 120):                                                # grid crosses
        for gy in range(0, H, 120):
            dr.line([(gx - 7, gy), (gx + 7, gy)], fill=(230, 233, 229, 34), width=2)
            dr.line([(gx, gy - 7), (gx, gy + 7)], fill=(230, 233, 229, 34), width=2)
    return im


def contours() -> Image.Image:
    rng = np.random.default_rng(SEED + 1)
    f = _field(rng)
    f = (f - f.min()) / (f.max() - f.min())
    q = np.floor(f * 34).astype(np.int32)
    edge = np.zeros((H, W), bool)
    edge[:, 1:] |= q[:, 1:] != q[:, :-1]
    edge[1:, :] |= q[1:, :] != q[:-1, :]
    major = edge & (np.maximum(q, np.roll(q, 1, 1)) % 5 == 0)
    a = np.zeros((H, W), np.uint8)
    a[edge] = 40
    a[major] = 70
    alpha = Image.fromarray(a, "L").filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.GaussianBlur(0.7))
    im = Image.new("RGBA", (W, H), LINE + (0,))
    im.putalpha(alpha)
    # dashed telegraph line across the map with small square station ticks (decoration, not to scale, no real route)
    dr = ImageDraw.Draw(im, "RGBA")
    pts = []
    for i in range(0, 241):
        t = i / 240
        px = W * (0.92 - 0.84 * t) + 70 * np.sin(t * 6.0)
        py = H * (0.06 + 0.88 * t)
        pts.append((px, py))
    for i in range(0, len(pts) - 1, 2):
        dr.line([pts[i], pts[i + 1]], fill=LINE + (64,), width=4)
    for i in range(6, len(pts), 22):
        px, py = pts[i]
        dr.rectangle([px - 9, py - 9, px + 9, py + 9], outline=LINE + (80,), width=3)
    return im


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    base().save(OUT / "base.jpg", quality=90)
    contours().save(OUT / "contours.png", optimize=True)
    (OUT / "LICENSE.md").write_text(
        "# Frontlore background\n\nbase.jpg and contours.png: own work, generated by brands/military_history/make_background.py "
        "(numpy, Pillow) on 2026-10-30. No third-party material, no AI images.\n", encoding="utf-8")
    print("written", sorted(p.name for p in OUT.iterdir()))

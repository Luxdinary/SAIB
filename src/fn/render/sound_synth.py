# --- small helpers ----------------------------------------------------------------------------------

def _t(n: int) -> np.ndarray:
    return np.arange(n) / SR


def _db(x: float) -> float:
    return float(10 ** (x / 20))


def normalize(x: np.ndarray, peak_db: float = SFX_PEAK_DB) -> np.ndarray:
    peak = float(np.max(np.abs(x))) if len(x) else 0.0
    return x * (_db(peak_db) / peak) if peak > 0 else x


def bump(u: np.ndarray, a: float, b: float) -> np.ndarray:
    """Beta-like hump on u in [0, 1]: u^a * (1-u)^b, scaled to peak 1 (a controls the attack, b the tail)."""
    u = np.clip(u, 0.0, 1.0)
    y = u ** a * (1.0 - u) ** b
    m = float(np.max(y)) if len(y) else 0.0
    return y / m if m > 0 else y


def env_ad(n: int, attack: float, decay: float) -> np.ndarray:
    """Linear attack, exponential decay (seconds)."""
    t = _t(n)
    return np.clip(t / max(attack, 1e-4), 0, 1) * np.exp(-np.maximum(t - attack, 0) / max(decay, 1e-4))


def fade(x: np.ndarray, fade_in: float = 0.0, fade_out: float = 0.0) -> np.ndarray:
    y = x.copy()
    n_in, n_out = int(fade_in * SR), int(fade_out * SR)
    if n_in > 0:
        ramp = 0.5 - 0.5 * np.cos(np.pi * np.arange(min(n_in, len(y))) / n_in)
        y[: len(ramp)] *= ramp if y.ndim == 1 else ramp[:, None]
    if n_out > 0:
        ramp = 0.5 + 0.5 * np.cos(np.pi * np.arange(min(n_out, len(y))) / n_out)
        y[len(y) - len(ramp):] *= ramp if y.ndim == 1 else ramp[:, None]
    return y


def stft_filter(x: np.ndarray, fc, bw_oct, n_fft: int = 2048, hop: int = 512) -> np.ndarray:
    """Time-varying band-pass: a Gaussian mask (width `bw_oct` octaves) around `fc` Hz per frame.

    `fc` and `bw_oct` are scalars or arrays over the signal (interpolated to the frames). sqrt-Hann analysis
    and synthesis windows at 75 % overlap; frame-wise rFFT, so a one-second sweep costs about 100 frames.
    """
    win = np.hanning(n_fft + 1)[:-1]
    wa = np.sqrt(win)
    pad = n_fft
    xp = np.concatenate([np.zeros(pad), x, np.zeros(pad + n_fft)])
    n_frames = 1 + (len(xp) - n_fft) // hop
    idx = np.arange(n_fft)[None, :] + hop * np.arange(n_frames)[:, None]
    spec = np.fft.rfft(xp[idx] * wa, axis=1)
    freqs = np.fft.rfftfreq(n_fft, 1 / SR)
    lf = np.log2(np.maximum(freqs, 1.0))
    centre = (hop * np.arange(n_frames) + n_fft / 2 - pad) / max(1, len(x))
    u = np.clip(centre, 0.0, 1.0)
    fc = np.atleast_1d(np.asarray(fc, dtype=float))
    bw = np.atleast_1d(np.asarray(bw_oct, dtype=float))
    fcf = np.interp(u, np.linspace(0, 1, len(fc)), fc) if len(fc) > 1 else np.full(n_frames, fc[0])
    bwf = np.interp(u, np.linspace(0, 1, len(bw)), bw) if len(bw) > 1 else np.full(n_frames, bw[0])
    mask = np.exp(-0.5 * ((lf[None, :] - np.log2(fcf)[:, None]) / (bwf[:, None] / 2.0)) ** 2)
    yf = np.fft.irfft(spec * mask, n=n_fft, axis=1) * wa
    y = np.zeros_like(xp)
    for k in range(n_frames):
        y[k * hop:k * hop + n_fft] += yf[k]
    y = y[pad:pad + len(x)]
    return y / (np.sum(win) / hop)          # constant-overlap-add gain of the Hann window at this hop


def lowpass_fft(x: np.ndarray, cutoff: float, width_oct: float = 1.0) -> np.ndarray:
    """Whole-signal low-pass with a smooth roll-off (raised cosine over `width_oct` octaves above `cutoff`)."""
    n = len(x)
    spec = np.fft.rfft(x)
    f = np.fft.rfftfreq(n, 1 / SR)
    lf = np.log2(np.maximum(f, 1.0))
    c0, c1 = np.log2(cutoff), np.log2(cutoff) + width_oct
    g = np.where(lf <= c0, 1.0, np.where(lf >= c1, 0.0, 0.5 + 0.5 * np.cos(np.pi * (lf - c0) / (c1 - c0))))
    return np.fft.irfft(spec * g, n=n)


def write_wav(path: Path, x: np.ndarray, sr: int = SR, bits: int = 16) -> Path:
    """Write mono (n,) or stereo (n, 2) floats in [-1, 1] as PCM WAV (16 or 24 bit)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    y = np.clip(np.asarray(x, dtype=np.float64), -1.0, 1.0)
    channels = 1 if y.ndim == 1 else y.shape[1]
    if bits == 24:
        ints = np.round(y * 8388607.0).astype("<i4")
        raw = ints.reshape(-1).view(np.uint8).reshape(-1, 4)[:, :3].tobytes()
        width = 3
    else:
        raw = np.round(y * 32767.0).astype("<i2").reshape(-1).tobytes()
        width = 2
    with wave.open(str(path), "wb") as fh:
        fh.setnchannels(channels)
        fh.setsampwidth(width)
        fh.setframerate(sr)
        fh.writeframes(raw)
    return path



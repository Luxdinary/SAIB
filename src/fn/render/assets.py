"""Asset layer for direction renders (Fassung B): video loops as scene backgrounds, a hero clip in the hook.

A plan declares assets by file name relative to brands/<id>/assets/higgsfield/ (or an absolute path):

    "assets": {
      "background": {"cinematic_hook": "bg_hook_dataroom.mp4", "data_flow": "bg_flow_lanes.mp4", ...},
      "hero": {"b1": "hero_document_to_chat.mp4"},
      "transition": "transition_cyan_sweep.mp4",
      "scrim": 0.55
    }

Rules: a missing file is a hard problem (never silently skipped); every used clip needs a licence line in
LICENSE.md next to the clips (`<file>: <licence text>`), otherwise the licence check fails. Logo, text,
captions and diagrams stay in the renderer; clips are muted and sit on track 0 below the scenes.
"""
from __future__ import annotations

import html
from dataclasses import dataclass, field
from pathlib import Path

from ..brands import Brand
from ..direction.story import DirectionPlan

LICENSE_FILE = "LICENSE.md"


@dataclass
class Clip:
    key: str            # scene_type for backgrounds, beat id for heroes, "transition"
    role: str           # background | hero | transition
    path: Path
    license: str = ""
    placeholder: bool = False   # file not there yet: the director draws a generated stand-in

    @property
    def name(self) -> str:
        return self.path.name


@dataclass
class Sfx:
    at: float           # absolute video time in seconds
    path: Path
    volume: float = 0.5
    license: str = ""

    @property
    def name(self) -> str:
        return self.path.name


@dataclass
class AssetSet:
    clips: list[Clip] = field(default_factory=list)
    scrim: float = 0.55
    problems: list[str] = field(default_factory=list)
    sfx: list[Sfx] = field(default_factory=list)   # optional sound-effect track; independent of `enabled`

    def background_for(self, scene_type: str) -> Clip | None:
        return next((c for c in self.clips if c.role == "background" and c.key == scene_type), None)

    def hero_for(self, beat_id: str) -> Clip | None:
        return next((c for c in self.clips if c.role == "hero" and c.key == beat_id), None)

    @property
    def transition(self) -> Clip | None:
        return next((c for c in self.clips if c.role == "transition"), None)

    @property
    def enabled(self) -> bool:
        return bool(self.clips)

    @property
    def placeholders(self) -> list[Clip]:
        return [c for c in self.clips if c.placeholder]

    def manifest_entries(self) -> tuple[list[dict], list[dict]]:
        real = [c for c in self.clips if not c.placeholder]
        assets = [{"name": f"clip:{c.name}", "kind": "video", "role": c.role, "key": c.key} for c in real]
        assets += [{"name": f"placeholder:{c.name}", "kind": "generated-gradient", "role": c.role, "key": c.key} for c in self.placeholders]
        licenses = [{"asset": f"clip:{c.name}", "license": c.license, "proof": str(c.path.parent / LICENSE_FILE)} for c in real if c.license]
        licenses += [{"asset": f"placeholder:{c.name}", "license": "generated by the renderer (CSS gradient), no third-party material", "proof": "fn.render.assets"} for c in self.placeholders]
        for s in {s.name: s for s in self.sfx}.values():
            assets.append({"name": f"sfx:{s.name}", "kind": "audio", "role": "sfx"})
            if s.license:
                licenses.append({"asset": f"sfx:{s.name}", "license": s.license, "proof": str(s.path.parent / LICENSE_FILE)})
        return assets, licenses


def _licenses(folder: Path) -> dict[str, str]:
    f = folder / LICENSE_FILE
    out: dict[str, str] = {}
    if not f.exists():
        return out
    for line in f.read_text(encoding="utf-8").splitlines():
        if ":" in line and not line.lstrip().startswith("#"):
            name, text = line.split(":", 1)
            out[name.strip().strip("`*- ")] = text.strip()
    return out


def resolve_assets(plan: DirectionPlan, brand: Brand, plan_assets: dict | None = None, *, allow_placeholders: bool = False) -> AssetSet:
    """Resolve the plan's asset declaration to files; missing files and licences become problems.

    With `allow_placeholders` a missing clip becomes a placeholder Clip (generated gradient) and a problem line
    that the report turns into a review finding, never into a silent omission.
    """
    spec = dict(plan_assets if plan_assets is not None else plan.assets or {})
    aset = AssetSet(scrim=float(spec.get("scrim", 0.55)))
    if not spec:
        return aset
    # "folder": clip folder relative to brands/<id>/ (default assets/higgsfield), e.g. "assets/clips" for own renders
    folder = brand.dir / spec.get("folder", "assets/higgsfield")

    def add(key: str, role: str, name: str) -> None:
        p = Path(name) if Path(name).is_absolute() else folder / name
        if not p.exists():
            aset.problems.append(f"asset missing: {role} {key} -> {p}" + (" (placeholder used)" if allow_placeholders else ""))
            if allow_placeholders:
                aset.clips.append(Clip(key=key, role=role, path=p, placeholder=True))
            return
        text = _licenses(p.parent).get(p.name, "")
        if not text:
            aset.problems.append(f"asset without licence line in {p.parent / LICENSE_FILE}: {p.name}")
        aset.clips.append(Clip(key=key, role=role, path=p, license=text))

    for scene_type, name in (spec.get("background") or {}).items():
        add(scene_type, "background", name)
    for beat_id, name in (spec.get("hero") or {}).items():
        add(beat_id, "hero", name)
    if spec.get("transition"):
        add("transition", "transition", spec["transition"])
    # "sfx": [{"at": 4.2, "file": "pop.wav", "volume": 0.4}, ...]; files relative to brands/<id>/<sfx_folder>
    sfx_folder = brand.dir / spec.get("sfx_folder", "assets/sfx")
    for k, e in enumerate(spec.get("sfx") or []):
        p = Path(e["file"]) if Path(e["file"]).is_absolute() else sfx_folder / e["file"]
        if not p.exists():
            aset.problems.append(f"sfx missing: #{k} at {e.get('at')} -> {p}")
            continue
        text = _licenses(p.parent).get(p.name, "")
        if not text:
            aset.problems.append(f"sfx without licence line in {p.parent / LICENSE_FILE}: {p.name}")
        aset.sfx.append(Sfx(at=float(e["at"]), path=p, volume=float(e.get("volume", 0.5)), license=text))
    return aset


def copy_assets(aset: AssetSet, project_assets: Path) -> dict[str, str]:
    """Copy clips into the project; returns {clip name: project-relative src}."""
    import shutil
    rel: dict[str, str] = {}
    (project_assets / "clips").mkdir(parents=True, exist_ok=True)
    for c in aset.clips:
        if c.placeholder:
            continue
        dst = project_assets / "clips" / c.name
        if not dst.exists():
            shutil.copy2(c.path, dst)
        rel[c.name] = f"assets/clips/{c.name}"
    return rel


def sfx_html(aset: AssetSet, project_assets: Path, total: float) -> list[str]:
    """Copy the sound effects into the project and return one <audio> clip per cue (tracks 8+, never above the voice)."""
    import shutil
    from .ffmpeg import audio_duration
    out: list[str] = []
    if not aset.sfx:
        return out
    (project_assets / "sfx").mkdir(parents=True, exist_ok=True)
    for k, s in enumerate(sorted(aset.sfx, key=lambda x: x.at)):
        dst = project_assets / "sfx" / s.name
        if not dst.exists():
            shutil.copy2(s.path, dst)
        dur = max(0.05, min(total - s.at, audio_duration(s.path) or 1.0))
        if s.at >= total:
            continue
        out.append(f'<audio id="sfx{k}" class="clip" src="assets/sfx/{html.escape(s.name)}" data-start="{s.at:.3f}" '
                   f'data-duration="{dur:.3f}" data-track-index="{8 + (k % 4)}" data-volume="{max(0.0, min(1.0, s.volume)):.2f}"></audio>')
    return out


def background_clip_html(sid: str, src: str, start: float, duration: float, *, loop_seconds: float | None = None) -> str:
    """A muted background video clip on track 0 under the scene, covering the frame."""
    extra = f' data-media-start="0"' if loop_seconds else ""
    return (f'<video id="{sid}-bg" class="clip bgclip" src="{html.escape(src)}" data-start="{start:.3f}" data-duration="{duration:.3f}" '
            f'data-track-index="0" data-volume="0" muted playsinline{extra}></video>')


def hero_clip_html(sid: str, src: str, start: float, duration: float) -> str:
    return (f'<video id="{sid}-hero" class="clip heroclip" src="{html.escape(src)}" data-start="{start:.3f}" data-duration="{duration:.3f}" '
            f'data-track-index="0" data-volume="0" muted playsinline></video>')


PLACEHOLDER_LOOKS = {   # generated stand-ins per scene type until the Higgsfield clips exist (no text, no logos)
    "cinematic_hook": "radial-gradient(ellipse at 50% 12%,color-mix(in srgb,{acc} 28%,transparent) 0%,transparent 45%)",
    "data_flow": "linear-gradient(180deg,color-mix(in srgb,{acc} 10%,transparent) 0%,transparent 30%),repeating-linear-gradient(90deg,transparent 0 330px,color-mix(in srgb,{acc} 9%,transparent) 330px 334px)",
    "ui_demo": "radial-gradient(ellipse at 50% 0%,color-mix(in srgb,{acc} 18%,transparent) 0%,transparent 40%)",
    "comparison": "linear-gradient(180deg,transparent 48%,color-mix(in srgb,{acc} 22%,transparent) 50%,transparent 52%)",
    "key_takeaway": "linear-gradient(180deg,color-mix(in srgb,{acc} 14%,transparent) 0%,transparent 28%)",
    "hero": "radial-gradient(circle at 30% 85%,color-mix(in srgb,{acc} 30%,transparent) 0%,transparent 35%)",
}


def placeholder_html(sid: str, scene_type_or_role: str, start: float, duration: float, acc: str) -> str:
    look = PLACEHOLDER_LOOKS.get(scene_type_or_role, PLACEHOLDER_LOOKS["key_takeaway"]).replace("{acc}", acc)
    return (f'<div id="{sid}-bg" class="clip bgph" data-start="{start:.3f}" data-duration="{duration:.3f}" data-track-index="0">'
            f'<div class="bgph-inner" style="background:{look}"></div></div>')


def assets_css(bg_hex: str, scrim: float) -> str:
    pct = int(max(0.0, min(1.0, scrim)) * 100)
    return f"""
.bgclip{{z-index:1;object-fit:cover;width:1080px;height:1920px;}}
.heroclip{{z-index:2;object-fit:cover;width:1080px;height:1920px;opacity:0.85;}}
.bgph{{z-index:1;}}
.bgph-inner{{position:absolute;inset:-120px;}}
#scrim{{position:absolute;inset:0;z-index:3;pointer-events:none;background:linear-gradient(180deg,color-mix(in srgb,{bg_hex} {max(0, pct - 35)}%,transparent) 0%,color-mix(in srgb,{bg_hex} {pct}%,transparent) 42%,color-mix(in srgb,{bg_hex} {min(100, pct + 30)}%,transparent) 100%);}}
"""
